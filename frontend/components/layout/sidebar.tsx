// Sidebar — the app shell's primary navigation.
//
// NAV mirrors preview/elevate-dental-os-v2.html `const NAV` (11 sections).
// Frozen Phase-0 primitive: section agents add screens behind these routes,
// they do not edit this file.
//
// RBAC: nav visibility is driven entirely by the effective permissions the
// backend returns from GET /auth/me (.permissions, a { key: boolean } map
// over the fixed catalogue). Each route id maps to a permission key in the
// shared lib/permissions module; an item shows only when its key is true.
// Overview routes have no key and are always visible. If /auth/me fails we
// treat the user as having no permissions (only Overview shows).

// Per-section stroke icons (lucide-style, 24-grid). Keeps the visual language
// on-theme — no new deps, inherits currentColor from the section header.
