function SectionIcon({ label }: { label: string }) {
  const d = SECTION_ICONS[label];
  if (!d) return null;
  return (
    <svg
      width="15"
      height="15"
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="1.9"
      strokeLinecap="round"
      strokeLinejoin="round"
      className="shrink-0"
      aria-hidden="true"
    >
      <path d={d} />
    </svg>
  );
}

function initials(name: string): string {
  return name
    .split(/[\s@.]+/)
    .filter(Boolean)
    .slice(0, 2)
    .map((p) => p[0]?.toUpperCase())
    .join('');
}

const MIN_W = 208;
const MAX_W = 384;
const DEFAULT_W = 256;
const WIDTH_KEY = 'sidebar:w';

export function Sidebar() {
  const pathname = usePathname();
  const { data: me } = useMe();

  const { collapsed, toggle: toggleCollapsed } = useSidebar();

  // Drag-to-resize width. Persisted to localStorage; clamped MIN..MAX.
  const [width, setWidth] = useState(DEFAULT_W);
  const [dragging, setDragging] = useState(false);

  useEffect(() => {
    const saved = Number(localStorage.getItem(WIDTH_KEY));
    if (saved >= MIN_W && saved <= MAX_W) setWidth(saved);
  }, []);

  const onMouseDown = useCallback((e: React.MouseEvent) => {
    e.preventDefault();
    setDragging(true);
  }, []);

  useEffect(() => {
    if (!dragging) return;
    const onMove = (e: MouseEvent) => {
      const w = Math.min(MAX_W, Math.max(MIN_W, e.clientX));
      setWidth(w);
    };
    const onUp = () => {
      setDragging(false);
      setWidth((w) => {
        localStorage.setItem(WIDTH_KEY, String(w));
        return w;
      });
    };
    document.addEventListener('mousemove', onMove);
    document.addEventListener('mouseup', onUp);
    document.body.style.cursor = 'col-resize';
    document.body.style.userSelect = 'none';
    return () => {
      document.removeEventListener('mousemove', onMove);
      document.removeEventListener('mouseup', onUp);
      document.body.style.cursor = '';
      document.body.style.userSelect = '';
    };
  }, [dragging]);

  const role = me?.role || 'reception';
  // Effective permissions from /auth/me. If the call failed (me === null),
  // permissions is null and only Overview routes resolve as visible.
  const permissions: Permissions | null = me?.permissions ?? null;

  const displayName = me?.full_name || me?.email || '';

  return (
    <aside
      style={{
        width: collapsed ? 0 : width,
        transition: dragging ? 'none' : 'width 0.18s ease',
      }}
      className={`relative shrink-0 bg-card h-screen sticky top-0 flex flex-col overflow-hidden ${
        collapsed ? 'border-0' : 'border-r border-border'
      }`}
    >
      {/* Brand header */}
      <div className="px-4 py-4 border-b border-border flex items-center gap-2.5">
        <div className="w-9 h-9 shrink-0 rounded-xl bg-gradient-to-br from-brand to-brand-700 text-white flex items-center justify-center font-display font-bold text-lg shadow-panel-sm">
          E
        </div>
        <Link href="/business-hub" className="leading-tight min-w-0 flex-1">
          <span className="block font-display text-[17px] font-semibold text-ink">Elevate</span>
          <span className="block text-[11px] uppercase tracking-[0.14em] text-ink-muted">
            Dental OS
          </span>
        </Link>
        <button
          onClick={toggleCollapsed}
          aria-label="Collapse sidebar"
          title="Collapse sidebar"
          className="shrink-0 w-8 h-8 -mr-1 rounded-lg text-ink-muted hover:text-brand hover:bg-bg flex items-center justify-center transition"
        >
          <HamburgerIcon />
        </button>
      </div>

      {/* Account switcher — agency actors only. Top-left, GHL-style: opens the
          one dialog that switches into a sub-account and manages it. */}
      <AgencyDialog />

      {/* Account picker — only for a login that belongs to several accounts.
          Separate from the agency dialog above: these are accounts the person
          is a MEMBER of, not sub-accounts they administer. */}
      <AccountPicker />

      {/* User card */}
      {me && (
        <div className="mx-3 mt-3 px-3 py-2.5 bg-bg rounded-xl flex items-center gap-2.5">
          <div className="w-8 h-8 shrink-0 rounded-full bg-brand-50 text-brand flex items-center justify-center text-xs font-semibold ring-1 ring-brand-100">
            {initials(displayName) || 'U'}
          </div>
          <div className="min-w-0">
            <div className="text-[13px] font-semibold text-ink truncate">{displayName}</div>
            <div className="text-[11px] text-ink-muted capitalize">{role.replace('_', ' ')}</div>
          </div>
        </div>
      )}

      {/* Nav — one row per section. The section's screens are not listed here;
          they are the tab strip at the top of the content area (SectionTabs),
          so this list stays one level deep however many screens a section
          grows. A row lands on the section's first VISIBLE item, so RBAC
          still decides where the click goes. */}
      <nav className="flex-1 overflow-y-auto p-3 space-y-0.5">
        {visibleNavSections(me?.role, permissions, me?.features).map((section) => {
          const active = section.items.some((i) => pathname === `/${i.id}`);
          const hasNew = section.items.some((i) => i.isNew);
          return (
            <Link
              key={section.label}
              href={`/${section.items[0].id}`}
              aria-current={active ? 'page' : undefined}
              className={`group relative flex items-center gap-2.5 rounded-lg px-3 py-2 text-[13px] transition-colors duration-150 ${
                active
                  ? 'bg-brand-50 font-semibold text-brand'
                  : 'font-medium text-ink-muted hover:bg-bg hover:text-ink'
              }`}
            >
              {/* active rail */}
              <span
                className={`absolute left-0 top-1/2 w-0.5 -translate-y-1/2 rounded-full bg-brand transition-all duration-150 ${
                  active ? 'h-5 opacity-100' : 'h-0 opacity-0 group-hover:h-3 group-hover:opacity-40'
                }`}
              />
              <SectionIcon label={section.label} />
              <span className="min-w-0 flex-1 truncate">{section.label}</span>
              {hasNew && !active && (
                <span className="ml-auto h-1.5 w-1.5 shrink-0 rounded-full bg-emerald-500" />
              )}
            </Link>
          );
        })}
      </nav>

      {/* Drag handle — stretch sidebar width */}
      {!collapsed && (
        <div
          role="separator"
          aria-orientation="vertical"
          onMouseDown={onMouseDown}
          onDoubleClick={() => {
            setWidth(DEFAULT_W);
            localStorage.setItem(WIDTH_KEY, String(DEFAULT_W));
          }}
          title="Drag to resize · double-click to reset"
          className="group absolute top-0 right-0 h-full w-1.5 translate-x-1/2 cursor-col-resize z-10"
        >
          <span
            className={`absolute inset-y-0 left-1/2 -translate-x-1/2 w-px transition-colors ${
              dragging ? 'bg-brand w-0.5' : 'bg-transparent group-hover:bg-brand-200'
            }`}
          />
        </div>
      )}
    </aside>
  );
}
